"""tools/schedule_mcp/server.py – the "department schedule" MCP server for StudyHub (read-only).

Launch (stdio): `python tools/schedule_mcp/server.py` from a venv where `mcp[cli]` is installed.
Data: data/schedule.json (generated by tools/schedule_mcp/make_schedule.py, invented).
"""
import json
from pathlib import Path

try:  # mcp 1.x
    from mcp.server.fastmcp import FastMCP
except ImportError:  # mcp >= 2: FastMCP was renamed MCPServer
    from mcp.server.mcpserver import MCPServer as FastMCP

DATA = Path(__file__).resolve().parents[2] / "data" / "schedule.json"
DAYS = {1: "Monday", 2: "Tuesday", 3: "Wednesday", 4: "Thursday", 5: "Friday"}

mcp = FastMCP("studyhub-schedule")


def load() -> dict:
    with DATA.open(encoding="utf-8") as fh:
        return json.load(fh)


def check_week(week: int) -> None:
    if not 1 <= week <= 18:
        raise ValueError(f"Week {week} is outside the semester; allowed range is 1 to 18.")


@mcp.tool()
def get_schedule(group: str, week: int) -> list[dict]:
    """Returns the classes of an academic group for a semester week. Read-only.

    Call this when you need to know when the group has classes.
    group: the group code as in the department schedule, e.g. "CS-22a".
    week: the semester week number, from 1 to 18.
    Result: a list of classes with day, period number, subject, instructor and room.
    """
    check_week(week)
    rows = [s for s in load()["slots"] if s["group"] == group and s["week"] == week]
    if not rows:
        raise ValueError(f'No classes found for group "{group}" in week {week}. '
                         'Check the code: it looks like "CS-22a".')
    return sorted(rows, key=lambda s: (s["day"], s["period"]))


@mcp.tool()
def find_free_slot(teacher: str, duration: int = 1, week: int = 1) -> list[dict]:
    """Finds an instructor's free periods for a semester week. Read-only.

    Call this when planning consultations or retakes.
    teacher: surname and initials as in the schedule, e.g. "Kovalenko O. M.".
    duration: how many consecutive periods are needed, from 1 to 3.
    week: the semester week number, from 1 to 18.
    Result: up to 10 options with the day and the number of the first period.
    """
    check_week(week)
    if not 1 <= duration <= 3:
        raise ValueError("duration must be from 1 to 3 consecutive periods.")
    data = load()
    known = {s["teacher"] for s in data["slots"]}
    if teacher not in known:
        raise ValueError(f'Instructor "{teacher}" is not in the schedule. '
                         'Name format: "Surname I. M.".')
    busy = {(s["day"], s["period"]) for s in data["slots"]
            if s["teacher"] == teacher and s["week"] == week}
    last = data["periods_per_day"] - duration + 1
    free = [{"day": DAYS[d], "start_period": p, "periods": duration}
            for d in DAYS for p in range(1, last + 1)
            if all((d, p + k) not in busy for k in range(duration))]
    return free[:10]


if __name__ == "__main__":
    mcp.run()  # stdio transport
